// deprecatedKeyExchangeSuitesOffered returns the names of the offered cipher
// suites in deprecatedKeyExchangeSuites, in the order the client sent them. It
// always returns a non-nil slice so JSON output renders [] rather than null.
func deprecatedKeyExchangeSuitesOffered(suites []uint16) []string {
	out := []string{}
	for _, ci := range suites {
		if name, found := deprecatedKeyExchangeSuites[ci]; found {
			out = append(out, name)
		}
	}
	return out
}
